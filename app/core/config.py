"""Service settings, read once from the environment (and `.env` locally)."""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path
from typing import Literal
from urllib.parse import urlsplit
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

from pydantic import Field, SecretStr, field_validator, model_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

SERVICE_NAME = "ai-twin"
DEFAULT_MODEL_INVENTORY = Path(__file__).resolve().parents[2] / "config" / "models.yaml"


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", extra="ignore")

    # --- service ---------------------------------------------------------
    app_env: Literal["local", "test", "dev", "prod"] = "local"
    # `vault` holds every tier and the admin routes; `public` serves published chunks only.
    deployment_profile: Literal["vault", "public"] = "vault"
    service_version: str = "0.1.0"
    host: str = "127.0.0.1"
    port: int = 8000
    reload: bool = False
    log_level: str = "INFO"
    log_format: Literal["json", "console", "auto"] = "auto"
    # OTLP/HTTP traces endpoint (e.g. http://localhost:4318/v1/traces); empty = spans stay local.
    otel_exporter_otlp_endpoint: str = ""

    # --- dependencies ------------------------------------------------------
    mongodb_uri: str = "mongodb://localhost:27018"
    mongodb_database: str = "ai_twin"
    redis_url: str = "redis://localhost:6380/0"
    qdrant_url: str = "http://localhost:6334"
    qdrant_api_key: SecretStr = SecretStr("")
    # Startup gives MongoDB this long to answer before failing fast.
    mongodb_timeout_ms: int = Field(default=5000, gt=0)
    # Each readiness check gets this long before it counts as unavailable.
    health_check_timeout_seconds: float = Field(default=1.0, gt=0, le=10)

    # --- models (llm-orchestrator) ------------------------------------------------
    # A provider whose key (or endpoint) is missing is treated as disabled, never as an error.
    groq_api_key: SecretStr | None = None
    cerebras_api_key: SecretStr | None = None
    gemini_api_key: SecretStr | None = None
    openrouter_api_key: SecretStr | None = None
    ollama_base_url: str = ""
    # Replaces the inventory's Ollama model name when set.
    ollama_model: str = ""
    typesafe_api_key: SecretStr | None = None
    jev_model: str = "jev-1.13.0"
    llm_timeout_seconds: float = Field(default=30.0, gt=0, le=300)
    # Local models (Ollama) on a CPU can take far longer to start answering a long prompt.
    llm_local_timeout_seconds: float = Field(default=120.0, gt=0, le=600)
    llm_max_attempts: int = Field(default=3, ge=1, le=10)
    model_inventory_path: Path = DEFAULT_MODEL_INVENTORY
    # Offline stand-in model for keyless local runs and tests.
    llm_mock_enabled: bool = False
    # --- storage -------------------------------------------------------------
    blob_dir: Path = Path("vault/blobs")
    # Fernet key (urlsafe base64, 32 bytes); generated by the setup script, never printed.
    blob_encryption_key: SecretStr = SecretStr("")
    # Visitors are known only by HMAC-SHA256(salt, ip); the raw address is never stored.
    visitor_hash_salt: SecretStr = SecretStr("")
    embedding_dim: int = Field(default=384, gt=0)
    conversation_cache_turns: int = Field(default=20, gt=0)
    public_conversation_retention_days: int = Field(default=90, gt=0)

    # --- ingestion -------------------------------------------------------------
    ingest_max_files: int = Field(default=20, gt=0, le=200)
    ingest_max_file_mb: int = Field(default=25, gt=0, le=500)
    ingest_workers: int = Field(default=2, ge=1, le=16)
    chunk_target_tokens: int = Field(default=400, ge=50, le=2000)
    chunk_overlap_tokens: int = Field(default=60, ge=0, le=500)
    url_fetch_timeout_seconds: float = Field(default=15.0, gt=0, le=120)
    # Local model files (spaCy, fastembed); excluded from vault export.
    models_dir: Path = Path("vault/models")
    # Owner-maintained, git-ignored employer denylist (see config/denylist.example.yaml).
    denylist_path: Path = Path("vault/config/denylist.yaml")
    # Comma-separated strings redaction keeps: the owner's published e-mail, phone, name.
    public_contact_allowlist: str = ""
    # Comma-separated `owner/name` list: the only repositories GitHub sync may read.
    github_sync_repos: str = ""
    github_token: SecretStr | None = None

    # --- retrieval and owner agent ----------------------------------------------
    retrieval_prefetch: int = Field(default=30, ge=1, le=200)
    retrieval_top_k: int = Field(default=6, ge=1, le=50)
    # Cross-encoder cut-off on a 0..1 (sigmoid) scale; weaker hits are dropped.
    rerank_min_score: float = Field(default=0.01, ge=0, le=1)
    owner_context_tokens: int = Field(default=3000, ge=200, le=32000)
    owner_history_turns: int = Field(default=8, ge=0, le=40)
    # How long POST /conversations/{id}/title waits before letting a slow model finish later.
    title_refresh_wait_seconds: float = Field(default=8.0, ge=0, le=60)
    # A rolling summary is refreshed in the background after this many new turns (0: only on
    # exit); long chats send it ahead of the recent turns within SUMMARY_CONTEXT_TOKENS.
    summary_every_turns: int = Field(default=6, ge=0, le=200)

    # --- owner intake assistant (vault) -----------------------------------------
    # Finished intake checkpoints older than this are pruned; a pending confirmation is kept.
    intake_checkpoint_days: int = Field(default=30, ge=1, le=3650)
    # `ingest_file` reads only from this folder, by file name.
    intake_inbox_dir: Path = Path("vault/inbox")
    # Natural dates ("yesterday", "12 Oct") resolve in this zone, day first.
    owner_timezone: str = "Asia/Kolkata"
    # After an ingest the assistant waits this long for the job before reporting its status.
    intake_ingest_wait_seconds: float = Field(default=30, ge=0, le=600)

    # --- public agent ----------------------------------------------------------
    # Per visitor (salted hash of the address the portfolio server forwards) and in total.
    public_messages_per_minute: int = Field(default=8, ge=1, le=1000)
    public_messages_per_day: int = Field(default=60, ge=1, le=100_000)
    # Protects the free model quotas: every visitor together, per UTC day.
    public_daily_message_cap: int = Field(default=1500, ge=1, le=1_000_000)
    # Input guard: longer messages are refused before anything else runs.
    public_max_message_chars: int = Field(default=800, ge=50, le=8000)
    # Prompt Guard 2 score (0..1) above which a message is blocked.
    prompt_guard_threshold: float = Field(default=0.5, gt=0, lt=1)
    # Scores from here up to the threshold are borderline: Jev gives a second opinion
    # when FF_JEV_ENABLED is on.
    prompt_guard_borderline: float = Field(default=0.2, ge=0, lt=1)
    public_context_tokens: int = Field(default=1500, ge=200, le=16000)
    # Earlier answered turns a public answer may read.
    public_history_turns: int = Field(default=4, ge=0, le=20)
    # Single-turn public answers are cached per normalised question and kb_public_version.
    public_answer_cache_ttl_seconds: int = Field(default=21_600, ge=0, le=7 * 86_400)
    # Public profile only: the resume PDF deploy-public provisions (the vault serves the
    # profile's resume blob instead).
    public_resume_path: Path | None = None
    # Shown in the assistant greeting and disclosure; empty means "the owner".
    public_owner_name: str = Field(default="", max_length=100)
    # Synced canary hashes (deploy-public provisions it); the vault reads MongoDB instead.
    public_canary_hashes_path: Path | None = None

    # --- opportunities: lead email (SMTP) -------------------------------------
    # Gmail: smtp.gmail.com, 587, starttls, an app password. Empty host = leads are stored
    # but not emailed until SMTP is configured.
    smtp_host: str = ""
    smtp_port: int = Field(default=587, ge=1, le=65535)
    smtp_username: str = ""
    smtp_password: SecretStr = SecretStr("")
    # starttls (587), tls (465) or none (a local debug server only).
    smtp_security: Literal["starttls", "tls", "none"] = "starttls"
    smtp_timeout_seconds: float = Field(default=20.0, gt=0, le=120)
    # The only recipient lead mail ever has; `From` is always LEAD_EMAIL_FROM (the owner's).
    lead_email_to: str = ""
    lead_email_from: str = ""

    # --- opportunities: capture in the public assistant -----------------------------
    # Turns the assistant spends gathering details before it falls back to the contact form.
    lead_max_turns: int = Field(default=6, ge=1, le=20)

    # --- opportunities: abuse controls and retention -----------------------------
    # Leads per visitor (salted address hash) per day, and every visitor together per UTC day.
    lead_visitor_daily_cap: int = Field(default=2, ge=1, le=100)
    lead_daily_cap: int = Field(default=30, ge=1, le=10_000)
    lead_retention_days: int = Field(default=365, ge=1, le=3650)
    # Cloudflare Turnstile secret; empty = submits are not verified (local development).
    turnstile_secret_key: SecretStr = SecretStr("")
    turnstile_verify_url: str = "https://challenges.cloudflare.com/turnstile/v0/siteverify"

    # --- observability: Langfuse tracing ----------------------------------------
    # All three set = traces go to Langfuse (Cloud Hobby or self-hosted); otherwise a no-op.
    langfuse_public_key: str = ""
    langfuse_secret_key: SecretStr = SecretStr("")
    langfuse_base_url: str = ""
    # Owner, intake, ingestion and title content is masked unless this is on; refused with a
    # Langfuse Cloud URL (owner text never goes to a third party).
    langfuse_owner_content: bool = False
    # Public questions and answers are traced with identifiers masked; false masks them too.
    langfuse_public_content: bool = True
    # Fraction of runs traced (the Hobby plan has a monthly quota).
    langfuse_sample_rate: float = Field(default=1.0, ge=0, le=1)

    # --- observability: security alert emails (SMTP settings shared with leads) ---------
    # The only alert recipient; empty = LEAD_EMAIL_TO. Always the owner's own address.
    alert_email_to: str = ""
    # One email per policy per cooldown: a storm sends one email and a count.
    alert_cooldown_minutes: int = Field(default=30, ge=1, le=24 * 60)
    # The daily digest goes after this hour (0-23) in OWNER_TIMEZONE.
    alert_digest_hour: int = Field(default=9, ge=0, le=23)
    alert_poll_seconds: float = Field(default=30.0, ge=1, le=3600)

    # --- observability: metrics ---------------------------------------------------
    # Public profile: GET /metrics needs this as a bearer token (unset = 404). The vault's is open.
    metrics_token: SecretStr = SecretStr("")

    # --- feature flags -------------------------------------------------------
    # Hosted classifier for non-sensitive decisions; capped at the public tier.
    ff_jev_enabled: bool = False

    @field_validator("owner_timezone")
    @classmethod
    def _known_zone(cls, value: str) -> str:
        try:
            ZoneInfo(value)
        except (ZoneInfoNotFoundError, ValueError) as exc:
            raise ValueError(f"Unknown time zone {value!r} (use an IANA name)") from exc
        return value

    @model_validator(mode="after")
    def _owner_content_self_hosted(self) -> Settings:
        if self.langfuse_owner_content and is_langfuse_cloud(self.langfuse_base_url):
            raise ValueError(
                "LANGFUSE_OWNER_CONTENT=true needs a self-hosted Langfuse; "
                "owner content is never sent to Langfuse Cloud"
            )
        return self


def is_langfuse_cloud(url: str) -> bool:
    host = urlsplit(url.strip()).hostname or ""
    return host == "langfuse.com" or host.endswith(".langfuse.com")


def ingest_max_bytes(settings: Settings) -> int:
    return settings.ingest_max_file_mb * 1024 * 1024


def split_list(raw: str) -> list[str]:
    return [part.strip() for part in raw.split(",") if part.strip()]


@lru_cache
def get_settings() -> Settings:
    return Settings()
