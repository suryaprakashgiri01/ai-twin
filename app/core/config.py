"""Service settings, read once from the environment (and `.env` locally)."""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path
from typing import Literal

from pydantic import Field, SecretStr
from pydantic_settings import BaseSettings, SettingsConfigDict

SERVICE_NAME = "ai-twin"
DEFAULT_MODEL_INVENTORY = Path(__file__).resolve().parents[2] / "config" / "models.yaml"


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", extra="ignore")

    # --- service ---------------------------------------------------------
    app_env: Literal["local", "test", "dev", "prod"] = "local"
    # `vault` holds every tier and the admin routes; `public` serves published chunks only.
    deployment_profile: Literal["vault", "public"] = "vault"
    service_version: str = "0.1.0"
    host: str = "127.0.0.1"
    port: int = 8000
    reload: bool = False
    log_level: str = "INFO"
    log_format: Literal["json", "console", "auto"] = "auto"

    # --- dependencies ------------------------------------------------------
    mongodb_uri: str = "mongodb://localhost:27018"
    mongodb_database: str = "ai_twin"
    redis_url: str = "redis://localhost:6380/0"
    qdrant_url: str = "http://localhost:6334"
    qdrant_api_key: SecretStr = SecretStr("")
    # Startup gives MongoDB this long to answer before failing fast.
    mongodb_timeout_ms: int = Field(default=5000, gt=0)
    # Each readiness check gets this long before it counts as unavailable.
    health_check_timeout_seconds: float = Field(default=1.0, gt=0, le=10)

    # --- models (llm-orchestrator) ------------------------------------------------
    # A provider whose key (or endpoint) is missing is treated as disabled, never as an error.
    groq_api_key: SecretStr | None = None
    cerebras_api_key: SecretStr | None = None
    gemini_api_key: SecretStr | None = None
    openrouter_api_key: SecretStr | None = None
    ollama_base_url: str = ""
    # Replaces the inventory's Ollama model name when set.
    ollama_model: str = ""
    typesafe_api_key: SecretStr | None = None
    jev_model: str = "jev-1.13.0"
    llm_timeout_seconds: float = Field(default=30.0, gt=0, le=300)
    llm_max_attempts: int = Field(default=3, ge=1, le=10)
    model_inventory_path: Path = DEFAULT_MODEL_INVENTORY
    # Offline stand-in model for keyless local runs and tests.
    llm_mock_enabled: bool = False
    # --- storage -------------------------------------------------------------
    blob_dir: Path = Path("vault/blobs")
    # Fernet key (urlsafe base64, 32 bytes); generated by the setup script, never printed.
    blob_encryption_key: SecretStr = SecretStr("")
    # Visitors are known only by HMAC-SHA256(salt, ip); the raw address is never stored.
    visitor_hash_salt: SecretStr = SecretStr("")
    embedding_dim: int = Field(default=384, gt=0)
    conversation_cache_turns: int = Field(default=20, gt=0)
    public_conversation_retention_days: int = Field(default=90, gt=0)

    # --- ingestion -------------------------------------------------------------
    ingest_max_files: int = Field(default=20, gt=0, le=200)
    ingest_max_file_mb: int = Field(default=25, gt=0, le=500)
    ingest_workers: int = Field(default=2, ge=1, le=16)
    chunk_target_tokens: int = Field(default=400, ge=50, le=2000)
    chunk_overlap_tokens: int = Field(default=60, ge=0, le=500)
    url_fetch_timeout_seconds: float = Field(default=15.0, gt=0, le=120)
    # Local model files (spaCy, fastembed); excluded from vault export.
    models_dir: Path = Path("vault/models")
    # Owner-maintained, git-ignored employer denylist (see config/denylist.example.yaml).
    denylist_path: Path = Path("vault/config/denylist.yaml")
    # Comma-separated strings redaction keeps: the owner's published e-mail, phone, name.
    public_contact_allowlist: str = ""
    # Comma-separated `owner/name` list: the only repositories GitHub sync may read.
    github_sync_repos: str = ""
    github_token: SecretStr | None = None

    # --- retrieval and owner agent ----------------------------------------------
    retrieval_prefetch: int = Field(default=30, ge=1, le=200)
    retrieval_top_k: int = Field(default=6, ge=1, le=50)
    # Cross-encoder cut-off on a 0..1 (sigmoid) scale; weaker hits are dropped.
    rerank_min_score: float = Field(default=0.01, ge=0, le=1)
    owner_context_tokens: int = Field(default=3000, ge=200, le=32000)
    owner_history_turns: int = Field(default=8, ge=0, le=40)

    # --- feature flags -------------------------------------------------------
    # Hosted classifier for non-sensitive decisions; capped at the public tier.
    ff_jev_enabled: bool = False


def ingest_max_bytes(settings: Settings) -> int:
    return settings.ingest_max_file_mb * 1024 * 1024


def split_list(raw: str) -> list[str]:
    return [part.strip() for part in raw.split(",") if part.strip()]


@lru_cache
def get_settings() -> Settings:
    return Settings()
