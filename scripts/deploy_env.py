"""Test against the deployed configuration from local: `python -m scripts.deploy_env pull|check`.

  pull            pull every GCP secret behind `ai-twin-*` into `.env.prod` (never printed;
                  redacted progress only, exactly like during deployment)
  check [--url URL] [--public-key KEY]
                  run the app's own readiness checks against `.env.prod` (the exact
                  QdrantCheck/RedisCheck/MongoCheck code `/readyz` uses), and optionally
                  smoke-test the live deployed service: livez 200, readyz 200,
                  /v1/me with public:read -> 200, /v1/chat -> 200.

`.env.prod` maps the cloud values onto the app's own names, so `AI_TWIN_ENV_FILE=.env.prod`
makes any local command (status, eval, chat, tests) read the deployed configuration instead
of the local stack. Never commit the file (already gitignored under `.env.*`).

Windows note: values are written as ASCII/LF with no trailing newline; the original deploy
hit a subtle bug where secrets carried a `\r` from CRLF `.env` lines and httpx rejected the
header. This script guarantees clean values at the source.
"""

from __future__ import annotations

import argparse
import asyncio
import shutil
import subprocess

import httpx

from app.core.config import Settings
from app.services.health import CheckStatus, default_checks, run_checks
from scripts._common import ROOT, fail, info, ok, read_env, warn

DOT_ENV_PATH = ROOT / ".env"

# Secret Manager name -> the name `.env.prod` uses (the app's own setting).
SECRET_MAP: dict[str, str] = {
    "ai-twin-mongodb-uri": "MONGODB_URI",
    "ai-twin-redis-url": "REDIS_URL",
    "ai-twin-qdrant-api-key": "QDRANT_API_KEY",
    "ai-twin-groq-api-key": "GROQ_API_KEY",
    "ai-twin-gemini-api-key": "GEMINI_API_KEY",
    "ai-twin-visitor-salt": "VISITOR_HASH_SALT",
    "ai-twin-blob-encryption-key": "BLOB_ENCRYPTION_KEY",
}
PROD_FILE = ROOT / ".env.prod"


def parse(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("pull", help="pull GCP secrets into .env.prod")
    check = sub.add_parser("check", help="verify the deployed configuration from local")
    check.add_argument(
        "--url",
        default="",
        help="live deployed service URL; set to also smoke-test its endpoints",
    )
    check.add_argument(
        "--public-key",
        default="",
        help="public:read API key for the live /v1/me and /v1/chat test (never printed)",
    )
    check.add_argument(
        "--chat-question",
        default="What is your experience with FastAPI?",
        help="question for the optional /v1/chat check",
    )
    check.add_argument(
        "--timeout",
        type=float,
        default=5.0,
        help="per-check timeout seconds for the local dependency probes (default 5)",
    )
    return parser.parse_args(argv)


def _clean(value: str) -> str:
    """Strip quotes, whitespace and the trailing `\r` CRLF files leave behind."""
    value = value.strip(" \"'")
    return value[:-1] if value.endswith("\r") else value


def _gcloud_binary() -> str:
    """Full path to gcloud: on Windows it is a .cmd/.ps1 shim, not an executable."""
    found = shutil.which("gcloud")
    if not found:
        raise RuntimeError("gcloud CLI not found on PATH")
    return found


def _secret(secret_name: str) -> str:
    """Access one Secret Manager version; the value is captured, never printed."""
    result = subprocess.run(
        [_gcloud_binary(), "secrets", "versions", "access", "latest", "--secret=" + secret_name],
        capture_output=True,
        text=True,
        check=False,
    )
    out = result.stdout.rstrip("\n\r")
    if result.returncode != 0 or not out:
        raise RuntimeError(
            f"gcloud secrets access failed for {secret_name}: " + result.stderr.strip()[:300]
        )
    return out


def cmd_pull() -> int:
    base = read_env(DOT_ENV_PATH)
    values: dict[str, str] = {"MONGODB_DATABASE": "ai_twin"}
    for secret_name, env_name in SECRET_MAP.items():
        values[env_name] = _secret(secret_name)
    qdrant_url = _clean(base.get("PUBLISH_QDRANT_URL", ""))
    if not qdrant_url:
        fail("PUBLISH_QDRANT_URL missing from .env; cannot mirror QDRANT_URL")
        return 1
    values["QDRANT_URL"] = qdrant_url
    values["DEPLOYMENT_PROFILE"] = "public"
    values["APP_ENV"] = "prod"
    for optional in ("CEREBRAS_API_KEY", "OPENAI_API_KEY", "OPENROUTER_API_KEY"):
        cleaned = _clean(base.get(optional, ""))
        if cleaned:
            values[optional] = cleaned
    lines = [
        '# Auto-generated by `make deploy-env ARGS="--pull"` from GCP Secret Manager.',
        "# Deployed-configuration mirror; never commit. Select it: AI_TWIN_ENV_FILE=.env.prod",
        "#",
        *[f"{key}={values[key]}" for key in sorted(values)],
    ]
    # ASCII, LF, no trailing `\r` in any value, single trailing newline.
    PROD_FILE.write_bytes(("\n".join(lines) + "\n").encode("ascii"))
    ok(f"wrote {PROD_FILE.name} ({len(values)} values; values never printed)")
    for key in sorted(values):
        info(f"  {key}<len={len(values[key])}>")
    return 0


async def _readiness(timeout_seconds: float) -> dict[str, CheckStatus]:
    settings = Settings(_env_file=str(PROD_FILE), health_check_timeout_seconds=timeout_seconds)
    checks = list(default_checks(settings))
    return await run_checks(checks, settings.health_check_timeout_seconds)


def _check_line(name: str, status: str) -> None:
    (ok if status == "ok" else fail)(f"readiness[{name}] = {status}")


async def smoke_live(url: str, public_key: str, question: str) -> int:
    failures: list[str] = []
    base = url.rstrip("/")
    if not public_key:
        # Fall back to the key stashed in .env.prod (never printed).
        public_key = read_env(PROD_FILE).get("AI_TWIN_PUBLIC_KEY", "").strip()
    async with httpx.AsyncClient(timeout=90) as client:
        for path, expected in (("/livez", 200), ("/readyz", 200), ("/admin/v1/whoami", 404)):
            try:
                response = await client.get(base + path)
                if response.status_code != expected:
                    failures.append(f"{path} -> {response.status_code} (expected {expected})")
            except Exception as exc:
                failures.append(f"{path} -> {type(exc).__name__}: {exc}")
        headers = {"X-API-Key": public_key} if public_key else {}
        if public_key:
            try:
                me = await client.get(base + "/v1/me", headers=headers)
                if me.status_code != 200:
                    failures.append(f"/v1/me -> {me.status_code} (expected 200)")
            except Exception as exc:
                failures.append(f"/v1/me -> {type(exc).__name__}: {exc}")
            try:
                chat = await client.post(
                    base + "/v1/chat",
                    params={"stream": "false"},
                    json={"message": question},
                    headers=headers,
                )
                if chat.status_code != 200:
                    failures.append(f"/v1/chat -> {chat.status_code} (expected 200)")
            except Exception as exc:
                failures.append(f"/v1/chat -> {type(exc).__name__}: {exc}")
        else:
            warn("no --public-key: skipped /v1/me and /v1/chat live checks")
    for line in failures:
        fail(line)
    if not failures:
        ok("live smoke test passed")
    return 1 if failures else 0


async def cmd_check(args: argparse.Namespace) -> int:
    if not PROD_FILE.exists():
        fail(f'{PROD_FILE.name} not found; run: make deploy-env ARGS="--pull"')
        return 1
    info(f"running /readyz-equivalent checks against {PROD_FILE.name}")
    results = await _readiness(args.timeout)
    status = 0
    for name, result_status in results.items():
        _check_line(name, result_status)
        if result_status != "ok":
            status = 1
    if args.url:
        live = await smoke_live(args.url, args.public_key, args.chat_question)
        if live:
            status = 1
    return status


def main(argv: list[str] | None = None) -> int:
    args = parse(argv)
    try:
        if args.command == "pull":
            return cmd_pull()
        return asyncio.run(cmd_check(args))
    except Exception as exc:
        fail(str(exc)[:600])
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
